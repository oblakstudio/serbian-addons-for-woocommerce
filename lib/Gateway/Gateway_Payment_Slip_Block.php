<?php
/**
 * Gateway_Payment_Slip_Block class file.
 *
 * @package Serbian Addons for WooCommerce
 * @subpackage Gateway
 */

namespace Oblak\WCSRB\Gateway;

use Automattic\WooCommerce\Blocks\Payments\Integrations\AbstractPaymentMethodType;

/**
 * Payment slip as a block checkout (Store API) payment method.
 *
 * Orders are still processed by Gateway_Payment_Slip - this only offers the method in the block checkout.
 *
 * @since 4.0.0
 */
class Gateway_Payment_Slip_Block extends AbstractPaymentMethodType {
    /**
     * Script handle of the payment method.
     *
     * @var string
     */
    public const SCRIPT_HANDLE = 'wcsrb-payment-slip-block';

    /**
     * Payment method name - same as the gateway ID.
     *
     * @var string
     */
    protected $name = Gateway_Payment_Slip::GW_ID;

    /**
     * Asset file generated by `npm run build:blocks` (script dependencies and version).
     *
     * @var string
     */
    protected string $asset_file;

    /**
     * Constructor
     *
     * @param Gateway_Payment_Slip|null $gateway Payment slip gateway. Default the plugin's, resolved on first use.
     */
    public function __construct( private ?Gateway_Payment_Slip $gateway = null ) {
        $this->asset_file = \WCRS_PLUGIN_PATH . 'dist/blocks/payment-slip/index.asset.php';
    }

    /**
     * Nothing to set up.
     *
     * The registry initializes integrations on `init` for every request, so the gateway is only
     * built once the block checkout asks for the method.
     */
    public function initialize(): void {
        // The gateway is resolved lazily by gateway().
    }

    /**
     * The method is offered when the gateway is enabled and usable (RSD store with a bank account).
     *
     * @return bool
     */
    public function is_active(): bool {
        return 'yes' === $this->gateway()->enabled && true === $this->gateway()->is_valid_for_use();
    }

    /**
     * Data for the payment method script (`wcsrb_payment_slip_data` setting).
     *
     * @return array{description: string, supports: array<int,string>, title: string}
     */
    public function get_payment_method_data(): array {
        return array(
            'description' => $this->gateway()->get_description(),
            'supports'    => $this->get_supported_features(),
            'title'       => $this->gateway()->get_title(),
        );
    }

    /**
     * Features the gateway supports.
     *
     * @return array<int,string>
     */
    public function get_supported_features(): array {
        return $this->gateway()->supports;
    }

    /**
     * Registers the payment method script.
     *
     * Without a build (no asset file) nothing is registered and the block checkout cannot offer the method.
     *
     * @return array<int,string>
     */
    public function get_payment_method_script_handles(): array {
        if ( ! \file_exists( $this->asset_file ) ) {
            return array();
        }

        $asset = include $this->asset_file;

        \wp_register_script(
            self::SCRIPT_HANDLE,
            \plugins_url( 'dist/blocks/payment-slip/index.js', \WCRS_PLUGIN_BASE ),
            $asset['dependencies'],
            $asset['version'],
            true,
        );
        \wp_set_script_translations(
            self::SCRIPT_HANDLE,
            'serbian-addons-for-woocommerce',
            \WCRS_PLUGIN_PATH . 'languages',
        );

        return array( self::SCRIPT_HANDLE );
    }

    /**
     * Get the payment slip gateway.
     *
     * @return Gateway_Payment_Slip
     */
    protected function gateway(): Gateway_Payment_Slip {
        return $this->gateway ??= \wcsrb_slip_gw();
    }
}
